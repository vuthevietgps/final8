// Local acceptance checks for price/cost snapshots. Never loads .env.
require('reflect-metadata');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const { Logger } = require('@nestjs/common');
Logger.overrideLogger(['error']);
const load = (file, name) => require(`../dist/${file}`)[name];
const Calculation = load('test-order2/services/order-calculation.service', 'OrderCalculationService');
const Orders = load('test-order2/test-order2.service', 'TestOrder2Service');
const Quotes = load('quote/quote.service', 'QuoteService');
const DeliveryService = load('delivery-status/delivery-status.service', 'DeliveryStatusService');
let connection;
let passed = 0;
const check = (name, expected, actual) => { assert.deepEqual(actual, expected, name); passed++; console.log(`PASS ${name}`); };
async function main() {
  const database = `erp_snapshot_check_${Date.now()}`;
  connection = await mongoose.createConnection(`mongodb://127.0.0.1:27027/${database}`, { serverSelectionTimeoutMS: 5000 }).asPromise();
  const model = (name, file) => connection.model(name, load(file, `${name}Schema`));
  const Product = model('Product', 'product/schemas/product.schema');
  const Order = model('TestOrder2', 'test-order2/schemas/test-order2.schema');
  const Quote = model('Quote', 'quote/schemas/quote.schema');
  const SupplierQuote = model('SupplierQuote', 'supplier-quote/schemas/supplier-quote.schema');
  const Delivery = model('DeliveryStatus', 'delivery-status/schemas/delivery-status.schema');
  model('ProductCategory', 'product-category/schemas/product-category.schema');
  const User = connection.model('User', new mongoose.Schema({ fullName: String, role: String }, { collection: 'users' }));
  const supplier = new mongoose.Types.ObjectId(), dealer = new mongoose.Types.ObjectId(), category = new mongoose.Types.ObjectId();
  await User.create([{ _id: dealer, fullName: 'Snapshot dealer', role: 'external_agent' }, { _id: supplier, fullName: 'Snapshot supplier', role: 'external_supplier' }]);
  await connection.collection('productcategories').insertOne({ _id: category, name: 'Snapshot category' });
  const product = async (extra = {}) => {
    const _id = new mongoose.Types.ObjectId();
    await Product.collection.insertOne({ _id, name: 'Snapshot product', categoryId: category, importPrice: 100000, shippingCost: 20000, packagingCost: 5000, isReturnable: false, ...extra });
    return _id;
  };
  const calc = new Calculation(Order, Product, Quote, SupplierQuote, new DeliveryService(Delivery, Order), { get: async () => undefined, set: async () => undefined });
  const service = new Orders(Order, Product, calc, {}, {}, { upsertForOrder: async () => undefined }, { triggerSyncOnOrderChange: async () => undefined }, { emit: () => undefined });
  const quotes = new Quotes(Quote, Product, {});
  const p = await product();
  const sq = (extra) => SupplierQuote.create({ productId: p, supplierId: supplier, approvalStatus: 'approved', price: 100000, effectiveAt: new Date('2026-01-01'), currency: 'VND', shippingFee: 20000, returnFee: 30000, ...extra });
  await sq({});
  const selected = await sq({ price: 120000, effectiveAt: new Date('2026-07-01') });
  await sq({ price: 999000, approvalStatus: 'pending', effectiveAt: new Date('2026-07-20') });
  await sq({ price: 888000, effectiveAt: new Date('2027-01-01') });
  const aq = (productId, extra = {}) => quotes.create({ productId: String(productId), agentId: String(dealer), product: 'Snapshot product', agentName: 'Snapshot dealer', unitPrice: 250000, status: 'Đã duyệt', validFrom: '2026-07-01', validUntil: '2026-12-31', ...extra });
  const selectedAgent = await aq(p);
  await aq(p, { unitPrice: 300000, validFrom: '2026-01-01' });
  const day = new Date('2026-08-01T05:00:00Z');
  await connection.collection('advertisingcosts').insertOne({ date: day, adGroupId: 'SNAPSHOT-ADS', spentAmount: 30000 });
  await connection.collection('laborcost1').insertOne({ date: day, cost: 20000 });
  await connection.collection('othercosts').insertOne({ date: day, amount: 10000 });
  const order = await service.create({ productId: String(p), supplierId: String(supplier), agentId: String(dealer), orderDate: day.toISOString(), quantity: 2, codAmount: 600000, orderStatus: 'Giao thành công', productionStatus: 'Đã trả kết quả', trackingNumber: 'LOCAL-SNAPSHOT', dealerShippingIncludedInPrice: true, adGroupId: 'SNAPSHOT-ADS', supplierAppliedPrice: 999999, agentAppliedPrice: 999999, agentQuoteId: 'spoofed' });
  check('nearest effective approved supplier price', [String(selected._id), 120000], [String(order.supplierQuoteId), order.supplierAppliedPrice]);
  check('nearest effective dealer price, not latest insertion', [String(selectedAgent._id), 250000], [order.agentQuoteId, order.agentAppliedPrice]);
  check('snapshot prices; successful dealer order charges outbound shipping', 250000, order.grossProfit);
  check('latest dated allocations and net profit', [30000, 20000, 10000, 190000, true], [order.advertisingCost, order.laborCostAllocation, order.otherCostAllocation, order.netProfit, !!order.costAllocatedAt]);
  await SupplierQuote.updateOne({ _id: selected._id }, { $set: { price: 700000, shippingFee: 80000 } });
  await Quote.updateOne({ _id: selectedAgent._id }, { $set: { unitPrice: 900000 } });
  await Product.updateOne({ _id: p }, { $set: { packagingCost: 50000 } });
  const renamed = await service.update(String(order._id), { customerName: 'Corrected name' });
  check('source edits and customer rename preserve all amounts', [120000, 250000, 20000, 5000, 190000], [renamed.supplierAppliedPrice, renamed.agentAppliedPrice, renamed.shippingFee, renamed.packagingCostSnapshot, renamed.netProfit]);
  const protectedOrder = await service.update(String(order._id), { supplierAppliedPrice: 1, agentAppliedPrice: 1, supplierQuoteId: new mongoose.Types.ObjectId(), agentQuoteId: 'spoofed' });
  check('PATCH cannot rewrite commercial snapshots', [120000, 250000, 190000], [protectedOrder.supplierAppliedPrice, protectedOrder.agentAppliedPrice, protectedOrder.netProfit]);
  await service.recalculateQuotes(String(order._id));
  check('repeat quote calculation preserves snapshots', 120000, (await Order.findById(order._id)).supplierAppliedPrice);
  await connection.collection('advertisingcosts').updateOne({ adGroupId: 'SNAPSHOT-ADS' }, { $set: { spentAmount: 40000 } });
  await calc.recalculateOrdersForDate(day);
  check('new source cost refreshes the corresponding allocation', 180000, (await Order.findById(order._id)).netProfit);
  const returned = await service.update(String(order._id), { orderStatus: 'Hàng hoàn', returnFee: 30000 });
  check('dealer return charges goods plus outbound and return fees even when shipping was included before', [500000, 240000, 50000, 550000, 180000, 'dealer', 'dealer_custody'], [returned.recognizedRevenue, returned.recognizedGoodsCost, returned.dealerRecoverableFees, returned.dealerContractAmount, returned.netProfit, returned.goodsOwner, returned.returnDisposition]);
  const stamp = returned.dealerSaleRecognizedAt.toISOString();
  const retryReturn = await service.update(String(order._id), { orderStatus: 'Hàng hoàn' });
  check('return retry does not duplicate fees or recognition', [550000, stamp], [retryReturn.dealerContractAmount, retryReturn.dealerSaleRecognizedAt.toISOString()]);
  const reship = await service.update(String(order._id), { orderStatus: 'Đang giao' });
  check('reshipping preserves the incurred return fee and dealer ownership', [550000, 30000, 'dealer'], [reship.dealerContractAmount, reship.dealerReturnFeeReceivable, reship.goodsOwner]);
  await User.updateOne({ _id: dealer }, { $set: { role: 'internal_agent' } });
  const internal = await service.update(String(order._id), { customerName: 'Dealer role changed' });
  check('dealer sale does not depend on internal/external login role', 180000, internal.netProfit);
  await assert.rejects(service.update(String(order._id), { agentId: new mongoose.Types.ObjectId() }), /Đơn đã xuất/);
  passed++; console.log('PASS dispatched dealer ownership cannot be reassigned');
  const retailP = await product({ packagingCost: 0, isReturnable: true });
  await sq({ productId: retailP, price: 120000, shippingFee: 20000, returnFee: 30000 });
  const retail = await service.create({ customerName: 'Retail four-case check', productId: String(retailP),
    supplierId: String(supplier), quantity: 1, orderDate: '2026-08-02T05:00:00Z', codAmount: 300000,
    orderStatus: 'Giao thành công', productionStatus: 'Đã trả kết quả', trackingNumber: 'RETAIL-LOCAL' });
  check('retail delivered: company owes supplier goods plus shipping', [300000, 120000, 140000, 160000],
    [retail.recognizedRevenue, retail.recognizedGoodsCost, retail.supplierContractAmount, retail.netProfit]);
  const retailReturned = await service.update(String(retail._id), { orderStatus: 'Hàng hoàn' });
  check('retail failed: no revenue, full supplier cost plus shipping and return fees', [0, 120000, 170000, -170000],
    [retailReturned.recognizedRevenue, retailReturned.recognizedGoodsCost, retailReturned.supplierContractAmount, retailReturned.netProfit]);
  const retailRetry = await service.update(String(retail._id), { customerName: 'Corrected retail customer' });
  check('retail failure costs survive an ordinary edit without duplicate charges', [170000, -170000],
    [retailRetry.supplierContractAmount, retailRetry.netProfit]);
  const bulkP = await product();
  await aq(bulkP, { applyToAllAgents: true });
  const bulk = { productId: bulkP, agentId: dealer, orderDate: day };
  await calc.calculateAgentQuote(bulk);
  check('bulk dealer quote ObjectId matches lookup', 250000, bulk.agentAppliedPrice);
  const futureP = await product();
  await aq(futureP, { validFrom: '2027-01-01', validUntil: '2027-12-31' });
  const future = { productId: futureP, agentId: dealer, orderDate: day };
  await calc.calculateAgentQuote(future);
  check('future dealer price is not substituted', undefined, future.agentQuoteId);
  const zeroP = await product();
  await sq({ productId: zeroP, price: 0, shippingFee: 0, returnFee: 0 });
  await aq(zeroP, { unitPrice: 0 });
  const zero = { productId: zeroP, supplierId: supplier, agentId: dealer, orderDate: day };
  await calc.calculateSupplierQuote(zero); await calc.calculateAgentQuote(zero); await calc.calculateShippingAndReturnFees(zero);
  check('zero is a valid quoted price and fee', [0, 0, 0, 0, false], [zero.supplierQuote, zero.agentQuote, zero.shippingFee, zero.returnFee, zero.supplierIsReturnableSnapshot]);
  const fallbackP = await product({ packagingCost: 0 });
  const fallback = { productId: fallbackP, supplierId: supplier, orderDate: day };
  await calc.calculateSupplierQuote(fallback); await calc.calculateShippingAndReturnFees(fallback);
  check('product fallback cost excludes shipping and records provenance', [100000, 20000, 'product_fallback'], [fallback.supplierQuote, fallback.shippingFee, fallback.supplierPriceSource]);
  await Product.updateOne({ _id: fallbackP }, { $set: { importPrice: 999000 } });
  await calc.calculateSupplierQuote(fallback);
  check('product fallback snapshot does not drift', 100000, fallback.supplierQuote);
  const usdP = await product();
  await sq({ productId: usdP, price: 10, currency: 'USD' });
  await assert.rejects(calc.calculateSupplierQuote({ productId: usdP, supplierId: supplier, orderDate: day }), /currency must be VND/);
  passed++; console.log('PASS foreign currency cannot silently become a VND cost');
  console.log(JSON.stringify({ passed, database, scope: 'price/cost snapshot phase; real services and isolated MongoDB, external side effects stubbed' }));
}
main().catch(error => { console.error(error.message); process.exitCode = 1; }).finally(async () => { if (connection) await connection.close(); });
